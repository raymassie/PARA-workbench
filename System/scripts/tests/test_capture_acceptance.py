from pathlib import Path
import copy
import hashlib
import importlib.util
import json
import subprocess
import sys
import tempfile
import unittest

SCRIPT = Path(__file__).resolve().parents[1] / 'check-capture.py'
spec = importlib.util.spec_from_file_location('capture_check', SCRIPT)
checker = importlib.util.module_from_spec(spec)
spec.loader.exec_module(checker)
hash_bytes = lambda data: hashlib.sha256(data).hexdigest()


class CaptureAcceptance(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.raw = b'PDF extraction\nchannel | power | uncorrectables\n1 | 4 | 120\n'
        self.original_home = '# Home\nManual intro\n## Status\nOld\n<!-- Generated by System/prompts/home-digest.md -->\n## Topics\nKeep me\n'
        self.write('04-archive/raw/2026-11-25-device.pdf', self.raw)
        self.write('04-archive/raw/old.pdf', b'older sealed capture')
        old_note = '# Device\nPrevious observations.\n'
        self.write('03-resources/device.md', old_note + '\n| channel | power | uncorrectables |\n| 1 | 4 | 120 |\n')
        self.write('Home.md', self.original_home.replace('Old\n', '[Device](03-resources/device.md)\n'))
        self.manifest = {'schema_version': 1,
            'capture': {'original_path': '00-raw/device.pdf', 'sha256': hash_bytes(self.raw), 'state': 'archived',
                        'archive_path': '04-archive/raw/2026-11-25-device.pdf',
                        'archive_before': {'04-archive/raw/old.pdf': hash_bytes(b'older sealed capture')}},
            'ideas': [{'id': 'device', 'state': 'filed', 'destinations': ['03-resources/device.md']}],
            'expected_coverage': ['table-channel', 'table-power', 'table-errors'],
            'coverage': [{'id': uid, 'idea_id': 'device', 'kind': 'table_column',
                          'destination': '03-resources/device.md', 'evidence_text': evidence}
                         for uid, evidence in [('table-channel', 'channel'), ('table-power', 'power'), ('table-errors', 'uncorrectables')]],
            'preserved_files': [],
            'existing_notes': [{'path': '03-resources/device.md', 'before_text': old_note, 'before_sha256': hash_bytes(old_note.encode())}],
            'indexes': [],
            'home': {'before_text': self.original_home, 'before_sha256': hash_bytes(self.original_home.encode()),
                     'generated_start': '## Status\n', 'generated_end': '<!-- Generated by System/prompts/home-digest.md',
                     'expected_links': ['03-resources/device.md'], 'refresh_checked': True}}

    def write(self, name, value):
        p = self.root / name
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(value if isinstance(value, bytes) else value.encode())

    def result(self, manifest=None):
        return checker.inspect_capture(self.root, self.manifest if manifest is None else manifest)

    def reject(self):
        self.assertNotEqual(self.result()['mechanical_verdict'], 'PASS')

    def test_complete_pdf_table_merge_without_git_or_index_passes(self):
        self.assertFalse((self.root/'.git').exists())
        self.assertEqual(self.result()['mechanical_verdict'], 'PASS')
        self.assertTrue(all(x.startswith('UNVERIFIED:') for x in self.result()['limits']))

    def test_pdf_table_column_removed_from_note_rejects(self):
        p = self.root/'03-resources/device.md'
        p.write_text(p.read_text().replace('uncorrectables', 'errors omitted'))
        self.reject()

    def test_declared_table_column_omitted_from_coverage_rejects(self):
        self.manifest['coverage'].pop()
        self.reject()

    def test_filed_idea_without_coverage_rejects(self):
        self.manifest['expected_coverage'] = []
        self.manifest['coverage'] = []
        self.reject()

    def test_incomplete_caller_inventory_is_explicitly_unverified(self):
        # Deliberately omit both inventory and evidence: helper cannot discover PDF semantics.
        self.manifest['expected_coverage'].pop()
        self.manifest['coverage'].pop()
        p = self.root/'03-resources/device.md'
        p.write_text(p.read_text().replace('uncorrectables', 'omitted'))
        result = self.result()
        self.assertEqual(result['mechanical_verdict'], 'PASS')
        self.assertIn('UNVERIFIED: completeness of caller-supplied pre-state and coverage inventory', result['limits'])

    def test_malformed_object_shapes_return_blocked(self):
        for key, value in [('capture', []), ('home', []), ('ideas', [None]), ('indexes', [None]), ('existing_notes', {})]:
            with self.subTest(key=key):
                manifest = copy.deepcopy(self.manifest)
                manifest[key] = value
                self.assertEqual(self.result(manifest)['mechanical_verdict'], 'BLOCKED')

    def test_prior_note_replaced_rejects(self):
        p = self.root/'03-resources/device.md'
        p.write_text(p.read_text().replace('Previous observations.', 'Replaced previous material'))
        self.reject()

    def test_raw_metadata_or_body_changed_rejects(self):
        for data in [self.raw+b'changed', b'---\ntags: [new]\n---\n'+self.raw]:
            with self.subTest(data=data):
                self.write('04-archive/raw/2026-11-25-device.pdf', data)
                self.reject()

    def test_collision_destination_preexisted_rejects(self):
        self.manifest['capture']['archive_before']['04-archive/raw/2026-11-25-device.pdf'] = hash_bytes(self.raw)
        self.reject()

    def test_sealed_neighbor_changed_rejects(self):
        self.write('04-archive/raw/old.pdf', b'overwritten')
        self.reject()

    def test_unaccounted_archive_file_rejects(self):
        self.write('04-archive/raw/extra.pdf', b'unaccounted')
        self.reject()

    def test_flagged_task_stays_in_inbox(self):
        (self.root/'04-archive/raw/2026-11-25-device.pdf').unlink()
        self.write('00-raw/device.pdf', self.raw)
        self.manifest['capture'] = {'original_path':'00-raw/device.pdf','sha256':hash_bytes(self.raw),'state':'task','reason':'Call supplier; no lasting reference value'}
        self.manifest['ideas'] = [{'id':'task','state':'flagged','reason':'Waiting on user'}]
        self.manifest['coverage'] = self.manifest['expected_coverage'] = []
        self.assertEqual(self.result()['mechanical_verdict'], 'PASS')
        self.manifest['capture']['archive_path'] = '04-archive/raw/2026-11-25-device.pdf'
        self.reject()

    def test_archived_flagged_task_rejects(self):
        self.manifest['ideas'].append({'id':'task','state':'flagged','reason':'Unfinished action'})
        self.reject()

    def test_unreadable_or_unresolved_capture_retained(self):
        for state in ['unreadable','unresolved']:
            with self.subTest(state=state):
                (self.root/'04-archive/raw/2026-11-25-device.pdf').unlink(missing_ok=True)
                self.write('00-raw/device.pdf', self.raw)
                m=copy.deepcopy(self.manifest)
                m['capture']={'original_path':'00-raw/device.pdf','sha256':hash_bytes(self.raw),'state':state,'reason':'Cannot recover input'}
                m['ideas']=[{'id':'unknown','state':'flagged','reason':'Needs access'}]
                m['coverage']=m['expected_coverage']=[]
                self.assertEqual(self.result(m)['mechanical_verdict'], 'PASS')

    def test_home_manual_sections_preserved(self):
        p=self.root/'Home.md'; p.write_text(p.read_text().replace('Keep me','Lost topics'))
        self.reject()

    def test_home_refresh_and_actual_links_required(self):
        self.manifest['home']['refresh_checked']=False
        self.reject()
        self.manifest['home']['refresh_checked']=True
        self.write('Home.md',self.original_home)
        self.reject()

    def test_only_qualifying_indexes_not_source_pages(self):
        self.write('03-resources/other.md','# Other\n')
        self.write('00-wiki/device.md','# Device\n[[03-resources/device]]\n[[03-resources/other]]\n')
        self.manifest['indexes']=[{'path':'00-wiki/device.md','qualifying_notes':['03-resources/device.md','03-resources/other.md']}]
        self.assertEqual(self.result()['mechanical_verdict'],'PASS')
        self.manifest['indexes'][0]['qualifying_notes']=['03-resources/device.md']
        self.reject()

    def test_substance_cannot_go_into_wiki(self):
        self.write('00-wiki/device.md','# Substance\n')
        self.manifest['ideas'][0]['destinations']=['00-wiki/device.md']
        self.reject()

    def test_traversal_and_symlink_escape_reject(self):
        self.manifest['ideas'][0]['destinations']=['../outside.md']
        self.reject()
        self.manifest['ideas'][0]['destinations']=['03-resources/device.md']
        p=self.root/'03-resources/device.md'; p.unlink(); p.symlink_to('/etc/hosts')
        self.reject()

    def test_unavailable_or_malformed_manifest_blocks(self):
        self.assertEqual(self.result({})['mechanical_verdict'],'BLOCKED')
        self.manifest['capture']['original_path']=None
        self.assertEqual(self.result()['mechanical_verdict'],'BLOCKED')

    def test_readonly_helper_and_cli(self):
        p=self.root/'manifest.json'; p.write_text(json.dumps(self.manifest))
        snapshot=lambda:{str(p.relative_to(self.root)):p.read_bytes() for p in self.root.rglob('*') if p.is_file()}
        before=snapshot(); self.result(); run=subprocess.run([sys.executable,'-B',str(SCRIPT),'--vault',str(self.root),'--manifest',str(p)],capture_output=True,text=True)
        self.assertEqual(run.returncode,0,run.stdout+run.stderr)
        self.assertEqual(snapshot(),before)
        self.assertTrue(json.loads(run.stdout)['process']['read_only'])


if __name__ == '__main__':
    unittest.main()
